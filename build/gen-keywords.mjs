// Regenerate src/keywords.js from the upstream vscode-lean4 TextMate grammar.
//
// The keyword set churns with the language (`grind_propagator`,
// `partial_fixpoint`, `reprove` are all recent additions), so we derive it
// instead of hand-copying it. Run `npm run gen` after a Lean release and
// commit the diff.

import { writeFileSync } from 'node:fs';

const SOURCE =
  'https://raw.githubusercontent.com/leanprover/vscode-lean4/master/vscode-lean4/syntaxes/lean4.json';

// hljs matches keywords with a single `$pattern` regex, so anything that is
// not a plain word token has to be dropped here and handled by a mode in
// lean4.js instead: `import all` (space), `by?` / `exact?%` / `binop%`
// (punctuation), `trace[...]` (embedded regex).
const WORD = /^#?[A-Za-z_][\w!']*$/;

const alternation = (src) => {
  // Peel the `\b(?<!\.)( ... )(?!\.)\b` scaffolding before splitting. Strip
  // the lookaround assertions FIRST: they contain parens of their own, so a
  // naive "up to the first (" would swallow `(?<!` and leave `?<!\.)(theorem`
  // as the first token.
  const body = src
    .replace(/\(\?<?[!=][^)]*\)/g, '')
    .replace(/^\\b/, '')
    .replace(/\\b$/, '')
    .replace(/^\((.*)\)$/s, '$1');
  return body.split('|').map((s) => s.trim());
};

const findByName = (patterns, name) =>
  patterns.filter((p) => p.name === name && typeof p.match === 'string');

const res = await fetch(SOURCE);
if (!res.ok) throw new Error(`${res.status} fetching ${SOURCE}`);
const grammar = JSON.parse(await res.text());
const pats = grammar.patterns;

const pick = (name) =>
  findByName(pats, name).flatMap((p) => alternation(p.match));

const clean = (xs) => [...new Set(xs.filter((w) => WORD.test(w)))].sort();

// `#print|#eval|...` is written without the leading `#` inside the group.
// Written as `#(print|eval|...)` — the `#` sits outside the group, so peel it
// off before splitting and put it back on each alternative.
const hashCommands = findByName(pats, 'keyword.other.lean4')
  .filter((p) => p.match.startsWith('#'))
  .flatMap((p) => alternation(p.match.replace(/^#/, '')).map((w) => `#${w}`));

const keywords = findByName(pats, 'keyword.other.lean4')
  .filter((p) => !p.match.startsWith('#'))
  .flatMap((p) => alternation(p.match));

const groups = {
  keyword: clean([...keywords, ...pick('storage.modifier.lean4')]),
  type: clean(pick('storage.type.lean4')),
  built_in: clean(hashCommands),
  literal: clean(pick('constant.language.lean4')),
  sorry: clean(pick('invalid.illegal.lean4')),
};

const dropped = [...keywords, ...hashCommands].filter((w) => !WORD.test(w));

const out = `// GENERATED by build/gen-keywords.mjs — do not edit by hand.
// Source: ${SOURCE}
// Regenerated: ${new Date().toISOString().slice(0, 10)}
//
// Dropped as non-word tokens (handled by modes in lean4.js, if at all):
// ${dropped.join(' ') || '(none)'}

export default ${JSON.stringify(groups, null, 2)};
`;

const dest = new URL('../src/keywords.js', import.meta.url);
writeFileSync(dest, out);

for (const [k, v] of Object.entries(groups)) {
  console.log(`${k.padEnd(9)} ${v.length}`);
}
console.log(`dropped   ${dropped.length}: ${dropped.join(' ')}`);
